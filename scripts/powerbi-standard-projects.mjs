const YEAR_OPTIONS = ["2026", "2025"];
const SCENARIO_OPTIONS = ["Base", "Upside", "Downside"];

function numericValue(value) {
  if (typeof value === "number") return value;
  const source = String(value).replaceAll(",", "").trim();
  const match = source.match(/[-+]?\d*\.?\d+/);
  const base = match ? Number(match[0]) : 0;
  const upper = source.toUpperCase();
  const scale = /B\b/.test(upper) ? 1e9 : /M\b/.test(upper) ? 1e6 : /K\b/.test(upper) ? 1e3 : 1;
  return base * scale;
}

const metric = (value, label, higherIsBetter) => {
  const normalizedValue = String(value).trim();
  const actual = numericValue(value);
  const isNeutral = higherIsBetter == null;
  const plan = isNeutral ? actual : actual * (higherIsBetter ? .98 : 1.02);
  const prior = isNeutral ? actual : actual * (higherIsBetter ? .92 : 1.09);
  const series = Array.from({ length: 12 }, (_, index) => prior + (actual - prior) * (index / 11));
  const format = normalizedValue.includes("$")
    ? "currency"
    : normalizedValue.includes("%")
      ? "percent"
      : /x$/i.test(normalizedValue)
        ? "multiple"
        : /(days|months)/i.test(label)
          ? "days"
          : "number";

  return {
    value,
    label,
    note: "Synthetic preview value.",
    format,
    higherIsBetter,
    plan,
    prior,
    series,
    sensitivity: isNeutral ? 0 : 1,
  };
};
const bar = (label, value) => ({ label, value });
const driver = (label, value, isRisk = false) => ({ label, value, isRisk });
const action = (owner, actionText) => ({ owner, action: actionText });
const page = (id, label) => ({ id, label });

function defineProject({
  id,
  scopeLabel,
  scopeOptions,
  breakdownLabel,
  breakdownOptions,
  governance,
  ...project
}) {
  return {
    id,
    route: `${id}/`,
    ...project,
    scopeLabel,
    scopeOptions,
    breakdownLabel,
    breakdownOptions,
    regionOptions: breakdownOptions,
    governance: [
      ...governance,
      "All displayed values are synthetic and public-safe.",
    ],
    yearOptions: YEAR_OPTIONS,
    scenarioOptions: SCENARIO_OPTIONS,
    defaults: {
      year: YEAR_OPTIONS[0],
      scenario: SCENARIO_OPTIONS[0],
      scope: scopeOptions[0],
      region: breakdownOptions[0],
    },
    filters: [
      { id: "year", label: "Year", options: YEAR_OPTIONS, default: YEAR_OPTIONS[0] },
      { id: "scenario", label: "Scenario", options: SCENARIO_OPTIONS, default: SCENARIO_OPTIONS[0] },
      { id: "scope", label: scopeLabel, options: scopeOptions, default: scopeOptions[0] },
      { id: "region", label: breakdownLabel, options: breakdownOptions, default: breakdownOptions[0] },
    ],
    dataClassification: "Synthetic public-safe preview data",
  };
}

